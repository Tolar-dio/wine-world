cache = json.load(open(OUT)) if os.path.exists(OUT) else {}
for k, q in Q.items():
    if k in cache and cache[k].get("q") == q:
        continue
    url = "https://nominatim.openstreetmap.org/search?" + urllib.parse.urlencode({"q": q, "format": "json", "limit": 3, "addressdetails": 0})
    r = subprocess.run(["curl", "-sS", "-m", "30", "-A", "VitisMundiAtlas/1.0 (research)", url], capture_output=True, text=True)
    try:
        res = json.loads(r.stdout)
    except Exception:
        res = []
    cache[k] = {"q": q, "res": [{"lat": float(x["lat"]), "lon": float(x["lon"]), "name": x.get("display_name", "")[:140], "cls": x.get("class"), "type": x.get("type")} for x in res]}
    json.dump(cache, open(OUT, "w"), indent=1, ensure_ascii=False)
    time.sleep(1.1)
print(len(cache), "cached;", sum(1 for v in cache.values() if v["res"]), "with hits")
