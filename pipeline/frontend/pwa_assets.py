#!/usr/bin/env python3
"""PWA files for the GitHub Pages build (called by build.py; can also run alone):
dist-gh/manifest.webmanifest, dist-gh/sw.js, dist-gh/icons/*.png (drawn here with Pillow).

The icon is the atlas in miniature: a night globe with a gold rim, a faint graticule and the two wine belts
(30 to 50 degrees north and south) in garnet.
"""
import hashlib
import json
import math
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path("/home/claude/winesite")
OCEAN = (15, 20, 34)
SPACE = (8, 11, 20)
GOLD = (224, 176, 76)
GARNET = (196, 74, 99)
GRAT = (154, 161, 178)


def draw_icon(size, maskable=False):
    S = 1024
    im = Image.new("RGBA", (S, S), SPACE + (255,))
    d = ImageDraw.Draw(im)
    # maskable icons keep everything inside the central 80% safe zone
    R = S * (0.34 if maskable else 0.43)
    cx = cy = S / 2
    tilt = math.radians(18)

    def proj(lat, lon):
        # orthographic globe, tilted towards the viewer by `tilt`
        la, lo = math.radians(lat), math.radians(lon)
        x = math.cos(la) * math.sin(lo)
        y = math.sin(la) * math.cos(tilt) - math.cos(la) * math.cos(lo) * math.sin(tilt)
        z = math.sin(la) * math.sin(tilt) + math.cos(la) * math.cos(lo) * math.cos(tilt)
        return cx + R * x, cy - R * y, z

    d.ellipse([cx - R, cy - R, cx + R, cy + R], fill=OCEAN + (255,))

    def layer(paint):
        lay = Image.new("RGBA", (S, S), (0, 0, 0, 0))
        paint(ImageDraw.Draw(lay))
        return lay
    # wine belts: front-facing parts of the 30-50 degree bands
    def belts(dd):
        for a, b in ((30, 50), (-50, -30)):
            for lon in range(-90, 90, 2):
                quad = [proj(a, lon), proj(a, lon + 2), proj(b, lon + 2), proj(b, lon)]
                if all(p[2] > -0.02 for p in quad):
                    dd.polygon([(p[0], p[1]) for p in quad], fill=GARNET + (215,))
    im = Image.alpha_composite(im, layer(belts))
    w = max(3, int(S * 0.0045))

    def grat(dd):
        for lat in (-60, -30, 0, 30, 60):
            pts = [(x, y) for x, y, z in (proj(lat, lon) for lon in range(-90, 91, 3)) if z > 0]
            if len(pts) > 1:
                dd.line(pts, fill=GRAT + (70,), width=w)
        for lon in (-60, -30, 0, 30, 60):
            pts = [(x, y) for x, y, z in (proj(lat, lon) for lat in range(-90, 91, 3)) if z > 0]
            if len(pts) > 1:
                dd.line(pts, fill=GRAT + (70,), width=w)
    im = Image.alpha_composite(im, layer(grat))
    d = ImageDraw.Draw(im)
    # gold rim
    rw = int(S * 0.024)
    d.ellipse([cx - R, cy - R, cx + R, cy + R], outline=GOLD + (255,), width=rw)
    # a single gold point: a vineyard at 45 degrees north
    x, y, _ = proj(45, 10)
    pr = S * 0.022
    d.ellipse([x - pr, y - pr, x + pr, y + pr], fill=GOLD + (255,))
    out = im.resize((size, size), Image.LANCZOS)
    return out.convert("RGB")


MANIFEST = {
    "name": "Vitis Mundi: an atlas of wine places",
    "short_name": "Vitis Mundi",
    "description": "An interactive globe atlas of the world's wine appellations, their boundaries, terrain, climate, vintages, grapes and history.",
    "start_url": "./",
    "scope": "./",
    "id": "./",
    "display": "standalone",
    "orientation": "any",
    "background_color": "#0f1422",
    "theme_color": "#0f1422",
    "categories": ["education", "food", "reference"],
    "icons": [
        {"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
        {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
        {"src": "icons/maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
    ],
}

SW = r"""/* Vitis Mundi service worker (generated by frontend/pwa_assets.py; build __BUILD__).
   The page: network first, cached copy when offline. Data and fonts: cached when used, refreshed in the
   background. Map tiles and terrain: cached when used, capped. Libraries from the CDN: cached (versioned URLs). */
const BUILD = '__BUILD__';
const C = { page: 'vm-page-1', data: 'vm-data-1', tiles: 'vm-tiles-1', libs: 'vm-libs-1' };
const CAP = { 'vm-data-1': 400, 'vm-tiles-1': 2500, 'vm-libs-1': 60 };
const SHELL = ['./', 'manifest.webmanifest', 'icons/icon-192.png', 'icons/icon-512.png'];
const TILE_HOSTS = /(^|\.)(tiles\.maps\.eox\.at|tile\.opentopomap\.org|s3\.amazonaws\.com|data\.geopf\.fr|wmts\.geo\.admin\.ch|mapsneu\.wien\.gv\.at|ign\.es|dgterritorio\.gov\.pt|nationalmap\.gov|service24\.rlp\.de|gds-srv\.hessen\.de|lgl-bw\.de|geoservices\.bayern\.de|geoportail\.lu|six\.nsw\.gov\.au|upload\.wikimedia\.org)$/;
const LIB_HOSTS = /^(cdn\.jsdelivr\.net|cdnjs\.cloudflare\.com|unpkg\.com|fonts\.googleapis\.com|fonts\.gstatic\.com)$/;

self.addEventListener('install', e => {
  e.waitUntil(caches.open(C.page).then(c => c.addAll(SHELL)).catch(() => null).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  const keep = new Set(Object.values(C));
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('vm-') && !keep.has(k)).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
async function trim(name) {
  const cap = CAP[name];
  if (!cap) return;
  const c = await caches.open(name);
  const keys = await c.keys();
  if (keys.length > cap) await Promise.all(keys.slice(0, keys.length - cap + Math.ceil(cap * 0.1)).map(k => c.delete(k)));
}
let trimT = {};
function later(name) { clearTimeout(trimT[name]); trimT[name] = setTimeout(() => trim(name), 4000); }
async function networkFirst(req, name) {
  const c = await caches.open(name);
  try {
    const res = await fetch(req);
    if (res && res.ok) c.put(req.mode === 'navigate' ? './' : req, res.clone());
    return res;
  } catch (err) {
    return (await c.match(req, { ignoreSearch: true })) || (await c.match('./')) || Response.error();
  }
}
async function cacheFirst(req, name, refresh) {
  const c = await caches.open(name);
  const hit = await c.match(req);
  const net = fetch(req).then(res => {
    // opaque responses are padded to megabytes of quota each: only the few library files may be opaque
    if (res && res.status !== 206 && (res.ok || (res.type === 'opaque' && name === C.libs))) { c.put(req, res.clone()); later(name); }
    return res;
  });
  if (hit) { if (refresh) net.catch(() => null); return hit; }
  return net.catch(() => Response.error());
}
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (req.mode === 'navigate') { e.respondWith(networkFirst(req, C.page)); return; }
  if (url.origin === self.location.origin) {
    if (/\/(data|fonts)\//.test(url.pathname)) { e.respondWith(cacheFirst(req, C.data, true)); return; }
    if (/\/(icons\/|manifest\.webmanifest)/.test(url.pathname)) { e.respondWith(cacheFirst(req, C.page, true)); return; }
    return;
  }
  if (LIB_HOSTS.test(url.hostname)) { e.respondWith(cacheFirst(req, C.libs, false)); return; }
  if (TILE_HOSTS.test(url.hostname)) { e.respondWith(cacheFirst(req, C.tiles, false)); return; }
});
"""


def write(dist: Path):
    dist.mkdir(parents=True, exist_ok=True)
    icons = dist / "icons"
    icons.mkdir(exist_ok=True)
    lines = []
    for name, size, mask in (("icon-192.png", 192, False), ("icon-512.png", 512, False), ("maskable-512.png", 512, True),
                             ("apple-touch-icon.png", 180, True), ("icon-32.png", 32, False)):
        draw_icon(size, mask).save(icons / name, optimize=True)
    (dist / "manifest.webmanifest").write_text(json.dumps(MANIFEST, indent=1), encoding="utf-8")
    page = (dist / "index.html").read_bytes() if (dist / "index.html").exists() else b""
    build = hashlib.sha1(page).hexdigest()[:10]
    (dist / "sw.js").write_text(SW.replace("__BUILD__", build), encoding="utf-8")
    (dist / ".nojekyll").write_text("", encoding="utf-8")
    lines.append(f"wrote PWA files in {dist}: manifest.webmanifest, sw.js (build {build}), icons/ (5 PNG)")
    return lines


if __name__ == "__main__":
    for line in write(ROOT / "dist-gh"):
        print(line)
